"""Export per-task documentation to `docs/tasks/` mechanically from the task packages.

Usage:
    python -m evals.export_docs                 # regenerate docs/tasks/ in full
    python -m evals.export_docs --only feature/ingest --out /tmp/tasks

Every page is assembled ONLY from committed code and seeded artifacts, so the
docs can never drift from the tasks:

- `KIND` / `SUMMARY` module constants and the module docstring of the task's
  `generate.py` (the `Usage:` block is stripped).
- The literal `prompt.txt` and staged files of a `--seed 1` instance, generated
  into a temp dir. Staged `*.md` files (e.g. `data/schema.md`) are inlined.
- The full assert-suite roster, enumerated by running the task's grader against
  the instance with an EMPTY deliverable (the shared grader CLIs enumerate the
  whole suite even when the deliverable is missing: first check fails,
  dependents skip).
- The named naive-variant diagnoses from the instance's `solution/truth.json`.

Generation is seeded, so the export is deterministic: rerunning produces
byte-identical pages until a task package changes. Regenerate with `make
task-docs`, never edit the pages by hand (see the repo's generated-files
policy).
"""

from __future__ import annotations

import argparse
import importlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

CATEGORIES = ("feature", "training", "inference", "ops", "capstone")
KINDS = ("table", "dataset", "answers", "platform")
SEED = 1  # fixed so pages are stable across regenerations
EVALS_DIR = Path(__file__).resolve().parent
DEFAULT_OUT = EVALS_DIR.parent / "docs" / "tasks"
MARKER = (
    "<!-- Auto-generated by `python -m evals.export_docs` (make task-docs). "
    "Do not edit by hand. -->"
)


def discover() -> list[tuple[str, str]]:
    """All (category, task) packages, in category order then alphabetical."""
    found = []
    for cat in CATEGORIES:
        for pkg in sorted((EVALS_DIR / cat).iterdir()):
            if pkg.is_dir() and (pkg / "generate.py").is_file():
                found.append((cat, pkg.name))
    return found


def strip_usage(doc: str) -> str:
    """Drop the docstring's `Usage:` block (a header line plus its indented
    command lines), keeping the surrounding prose verbatim."""
    out, in_usage = [], False
    for line in doc.splitlines():
        if line.strip() == "Usage:":
            in_usage = True
            continue
        if in_usage and (not line.strip() or line.startswith("    ")):
            continue
        in_usage = False
        out.append(line)
    return "\n".join(out).strip()


def grader_shape(grade_src: str) -> str:
    """Which shared CLI shape the grader speaks, sniffed from its source:
    `answers` (--instance --answers), `platform` (--instance --adapter none),
    or `table` (--instance --csv|--adapter) — the default also covers the
    custom table-shaped graders (e.g. `pit`)."""
    if "grade_answers_main" in grade_src:
        return "answers"
    if "grade_platform_main" in grade_src or "from evals.capstone.common import" in grade_src:
        return "platform"
    return "table"


def enumerate_asserts(cat: str, name: str, shape: str, instance: Path) -> list[str]:
    """Run the grader on the instance with an EMPTY deliverable and return the
    enumerated assert names. Runs in a subprocess with an empty cwd (platform
    graders read `submission/` from cwd) and tolerates the expected non-zero
    exit (the suite fails by construction, but it still enumerates)."""
    if shape == "answers":
        args = ["--answers", str(instance / "_missing.json")]
    elif shape == "platform":
        args = ["--adapter", "none"]
    else:
        args = ["--csv", str(instance / "_missing.csv")]
    with tempfile.TemporaryDirectory() as cwd:
        proc = subprocess.run(
            [sys.executable, "-m", f"evals.{cat}.{name}.grade", "--instance", str(instance), *args],
            capture_output=True,
            text=True,
            cwd=cwd,
        )
    try:
        report = json.loads(proc.stdout)
    except json.JSONDecodeError as e:
        raise RuntimeError(
            f"{cat}/{name}: grader emitted no report (stderr: {proc.stderr.strip()[:500]})"
        ) from e
    return [a["name"] for a in report["asserts"]]


def staged_files(instance: Path) -> list[Path]:
    """The files the agent sees, relative to the run dir: everything the
    generator staged except the answer key (`solution/`) and the runner
    metadata (`instance.json`)."""
    return sorted(
        p.relative_to(instance)
        for p in instance.rglob("*")
        if p.is_file() and p.parts[len(instance.parts)] != "solution" and p.name != "instance.json"
    )


def render(cat: str, name: str, instance: Path) -> str:
    gen = importlib.import_module(f"evals.{cat}.{name}.generate")
    grade_py = EVALS_DIR / cat / name / "grade.py"
    grade_doc = (importlib.import_module(f"evals.{cat}.{name}.grade").__doc__ or "").strip()
    shape = grader_shape(grade_py.read_text())
    kind = gen.KIND
    if kind not in KINDS:
        raise RuntimeError(f"{cat}/{name}: KIND {kind!r} not in {KINDS}")

    truth_path = instance / "solution" / "truth.json"
    truth = json.loads(truth_path.read_text()) if truth_path.exists() else {}
    diagnoses = truth.get("variant_diagnosis", {})
    asserts = enumerate_asserts(cat, name, shape, instance)
    files = staged_files(instance)
    grader_args = {
        "answers": "--instance <dir> --answers submission/answers.json",
        "platform": "--instance <dir> --adapter <platform|none>",
        "table": "--instance <dir> (--csv <file> | --adapter <platform>)",
    }[shape]

    lines = [
        MARKER,
        "",
        f"# {name} ({cat})",
        "",
        gen.SUMMARY.strip(),
        "",
        f"**Deliverable kind:** {kind}",
        "",
        f"**Grader:** `python -m evals.{cat}.{name}.grade {grader_args}`"
        + (f" — {grade_doc.splitlines()[0]}" if grade_doc else ""),
        "",
        "## Generator notes",
        "",
        strip_usage(gen.__doc__ or ""),
        "",
        f"## Prompt (seed {SEED})",
        "",
        "```text",
        (instance / "prompt.txt").read_text().rstrip("\n"),
        "```",
        "",
        "## Staged files",
        "",
    ]
    lines += [f"- `{f}`" for f in files if f.name != "prompt.txt"] or [
        "- (none besides the prompt)"
    ]
    for f in files:
        if f.suffix == ".md":
            lines += [
                "",
                f"### `{f}`",
                "",
                "````markdown",
                (instance / f).read_text().rstrip("\n"),
                "````",
            ]
    lines += [
        "",
        "## Assert suite",
        "",
        "Enumerated by running the grader against the seed-1 instance with an empty deliverable:",
        "",
    ]
    lines += [f"- `{a}`" for a in asserts]
    if diagnoses:
        lines += [
            "",
            "## Diagnosed naive variants",
            "",
            "On a content mismatch the grader compares against these precomputed "
            "known-wrong digests and names the failure:",
            "",
        ]
        lines += [f"- `{k}`: {v}" for k, v in diagnoses.items()]
    return "\n".join(lines) + "\n"


def render_index(pages: list[tuple[str, str]]) -> str:
    """`docs/tasks/README.md`: one roster table per category."""
    lines = [MARKER, "", "# Benchmark tasks", ""]
    lines += [
        "One generated page per task package under `evals/`. Each page holds the",
        "generator's own notes, the literal seed-1 prompt, the staged files, the",
        "enumerated assert suite, and the named naive-variant diagnoses.",
        "",
    ]
    for cat in CATEGORIES:
        rows = [(n, s) for c, n in pages if c == cat for s in [_summary(c, n)]]
        if not rows:
            continue
        lines += [f"## {cat}", "", "| Task | Kind | Summary |", "|---|---|---|"]
        for n, s in rows:
            kind = importlib.import_module(f"evals.{cat}.{n}.generate").KIND
            lines.append(f"| [`{n}`]({cat}/{n}.md) | {kind} | {s} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _summary(cat: str, name: str) -> str:
    return importlib.import_module(f"evals.{cat}.{name}.generate").SUMMARY.strip()


def export_task(cat: str, name: str, out_dir: Path) -> Path:
    gen = importlib.import_module(f"evals.{cat}.{name}.generate")
    with tempfile.TemporaryDirectory() as t:
        instance = Path(t) / "instance"
        gen.generate(SEED, instance)
        page = render(cat, name, instance)
    dest = out_dir / cat / f"{name}.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(page)
    return dest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--only", action="append", help="category/task (repeatable); default: all")
    args = ap.parse_args(argv)

    tasks = discover()
    if args.only:
        wanted = {tuple(o.split("/", 1)) for o in args.only}
        tasks = [t for t in tasks if t in wanted]
        missing = wanted - set(tasks)
        if missing:
            ap.error(f"unknown task(s): {sorted(missing)}")
    for cat, name in tasks:
        dest = export_task(cat, name, args.out)
        print(f"[task-docs] {dest}")
    if not args.only:
        (args.out / "README.md").write_text(render_index(tasks))
        print(f"[task-docs] {args.out / 'README.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
